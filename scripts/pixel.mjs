// Tiny pixel-art helpers: sprites and a 5x7 pixel font, rendered as SVG paths
// (one <path> per colour, so the files stay small).

export function sprite(rows, pal, s = 1, ox = 0, oy = 0) {
  const byColor = {};
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (!pal[ch]) { x++; continue; }
      let e = x;
      while (e < row.length && row[e] === ch) e++;
      (byColor[pal[ch]] ||= []).push(`M${ox + x * s} ${oy + y * s}h${(e - x) * s}v${s}h${-(e - x) * s}z`);
      x = e;
    }
  });
  return Object.entries(byColor).map(([c, d]) => `<path fill="${c}" d="${d.join('')}"/>`).join('');
}

