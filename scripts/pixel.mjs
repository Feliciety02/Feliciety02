export const GLYPHS = Object.fromEntries(Object.entries(G).map(([k, v]) => [k, v.split(' ')]));

export const textWidth = (str, s) => str.length * 6 * s - s;

/** Path data for pixel text whose top-left corner is (x, y). */
export function textD(str, x, y, s) {
  let d = '';
  [...str].forEach((ch, i) => {
    const g = GLYPHS[ch] || GLYPHS[ch.toUpperCase()] || GLYPHS['?'];
    const gx = x + i * 6 * s;
    const dy = 'gjpqy'.includes(ch) ? 2 * s : 0; // descenders
    g.forEach((row, r) => {
      let c = 0;
      while (c < 5) {
        if (row[c] !== '#') { c++; continue; }
        let e = c;
        while (e < 5 && row[e] === '#') e++;
        d += `M${gx + c * s} ${y + dy + r * s}h${(e - c) * s}v${s}h${-(e - c) * s}z`;
        c = e;
      }
    });
  });
  return d;
}

/** Pixel text with a 1-pixel drop shadow. */
export function text(str, x, y, s, fill, shadow) {
  let out = '';
  if (shadow) out += `<path fill="${shadow}" d="${textD(str, x + s, y + s, s)}"/>`;
  return out + `<path fill="${fill}" d="${textD(str, x, y, s)}"/>`;
}

export function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export const hash = (str) => [...str].reduce((h, c) => (Math.imul(h, 31) + c.charCodeAt(0)) >>> 0, 7);

/** A character canvas for drawing bigger pixel art procedurally. */
export class Grid {
  constructor(w, h) { this.w = w; this.h = h; this.c = Array.from({ length: h }, () => Array(w).fill('.')); }
  get(x, y) { return x >= 0 && y >= 0 && x < this.w && y < this.h ? this.c[y][x] : '.'; }
  set(x, y, ch) { x = Math.round(x); y = Math.round(y); if (x >= 0 && y >= 0 && x < this.w && y < this.h) this.c[y][x] = ch; return this; }
  rect(x, y, w, h, ch) { for (let j = y; j < y + h; j++) for (let i = x; i < x + w; i++) this.set(i, j, ch); return this; }
  disc(cx, cy, r, ch) {
    for (let j = Math.floor(cy - r); j <= cy + r; j++)
      for (let i = Math.floor(cx - r); i <= cx + r; i++)
        if ((i - cx) ** 2 + (j - cy) ** 2 <= r * r) this.set(i, j, ch);
    return this;
  }
  /** Paint ch on empty cells that touch a filled cell (4-neighbour outline). */
  outline(ch) {
    const add = [];
    for (let y = 0; y < this.h; y++) for (let x = 0; x < this.w; x++) {
      if (this.c[y][x] !== '.') continue;
      if ([[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => { const v = this.get(x + dx, y + dy); return v !== '.' && v !== ch; })) add.push([x, y]);
    }
    add.forEach(([x, y]) => this.set(x, y, ch));
    return this;
  }
  rows() { return this.c.map((r) => r.join('')); }
}

/** Dust the top-most pixel of every column with snow. */
export function snowify(rows, ch = 'w') {
  const out = rows.map((r) => [...r]);
  const w = Math.max(...rows.map((r) => r.length));
  for (let x = 0; x < w; x++) for (let y = 0; y < out.length; y++) if (out[y][x] && out[y][x] !== '.') { out[y][x] = ch; break; }
  return out.map((r) => r.join(''));
}
